export type Product = {
    id: number | string;
    productId?: number | string;
    name: string;
    image: string;
    price: string;
    sales?: {
        Weekly: number;
        Monthly: number;
        Yearly: number;
    };
    status?: string;
    quantity?: number | string;
    customer?: string;
    category?: string;
    desc?: string;
    sizeOptions?: {
        id: string;
        value: string;
        defaultChecked: boolean;
        status?: string;
    }[];
    colors?: {
        id: string;
        className: string;
        value: string;
    }[];
    sale?: number;
    stock?: string;
    startDate?: string;
    payment?: number; // payment as number
};

export type AttributeItem = {
    id: number;
    category: string;
    value: string;
    group: "TShirt" | "Pants" | "Hat";
    status: "Publish" | "Draft";
    viewHref?: string;
    editHref?: string;
};

export type Category = {
    id: number;
    name: string;
    image: string;
    quantity: number;
    sale: number;
    date: string;
    category: "TShirt" | "Pants" | "Hat";
    status: "Publish" | "Draft";
};


